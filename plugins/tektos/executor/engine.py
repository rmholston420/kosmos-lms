_CAPABILITY_TABLE: dict[str, ToolCategory] = {
    "terminal": "terminal",
    "execute_code": "terminal",
    "bash": "terminal",
    "read_file": "file_operations",
    "file_read": "file_operations",
    "write_file": "file_operations",
    "file_write": "file_operations",
    "file_list": "file_operations",
    "search_files": "search",
    "web_search": "web",
    "web_fetch": "web",
    "web_extract": "web",
    "delegate_task": "delegation",
}
"""Known tool → category mapping. Any tool name outside this table is
reported in :attr:`ToolRoute.unrouted_tools` at 8.5 (routing only; no
execution). MCP-based dynamic discovery deferred per ADR-107 D9."""


def _keyword_route(task_description: str) -> ToolRoute:
    """Verbatim port of donor ``ToolRouter.route_tool`` heuristic branches."""

    task_lower = task_description.lower()
    if any(k in task_lower for k in ("shell", "command", "execute", "run")):
        return ToolRoute(
            primary_tool="bash",
            fallback_tools=("execute_code",),
            category="terminal",
            reason="Task involves shell command execution",
        )
    if any(k in task_lower for k in ("read", "open", "view", "inspect")):
        return ToolRoute(
            primary_tool="file_read",
            fallback_tools=("bash",),
            category="file_operations",
            reason="Task involves reading file contents",
        )
    if any(k in task_lower for k in ("write", "create", "save", "edit")):
        return ToolRoute(
            primary_tool="file_write",
            fallback_tools=("bash",),
            category="file_operations",
            reason="Task involves writing file contents",
        )
    if any(k in task_lower for k in ("search", "find", "grep")):
        return ToolRoute(
            primary_tool="search_files",
            fallback_tools=("bash",),
            category="search",
            reason="Task involves searching files",
        )
    if any(k in task_lower for k in ("web", "internet", "online")):
        return ToolRoute(
            primary_tool="web_search",
            fallback_tools=("web_extract",),
            category="web",
            reason="Task involves web search",
        )
    if any(k in task_lower for k in ("delegate", "subagent", "parallel")):
        return ToolRoute(
            primary_tool="delegate_task",
            fallback_tools=("bash",),
            category="delegation",
            reason="Task involves delegation",
        )
    return ToolRoute(
        primary_tool="bash",
        fallback_tools=("execute_code",),
        category="terminal",
        reason="Default routing for unknown task type",
    )


class TektosToolRouter:
    """Kosmos Tektos tool-router (ADR-107 D1).

    Two modes:

    * ``route(session_id, task_description)`` — keyword-match a natural-language
      task description to a single ``ToolRoute`` (donor
      ``ToolRouter.route_tool`` behavior).
    * ``route_for_tools(session_id, tools_needed, task_description)`` — map a
      ``SubTask.tools_needed`` tuple (from Stage 8.4 ``DecompositionPlan``)
      to a ``ToolRoute`` identifying which tools are known (``matched_tools``)
      versus unknown at 8.5 (``unrouted_tools``).

    Never raises (fail-open per ADR-107 D9); returns a synthetic route with
    ``category='unknown'`` on unexpected error.
    """

    def __init__(
        self,
        *,
        relational_memory: _RelationalMemoryLike | None = None,
        event_bus: _EventBusLike | None = None,
        max_records: int = 100,
    ) -> None:
        self._relational_memory = relational_memory
        self._event_bus = event_bus
        self._buffer: deque[ToolRoute] = deque(maxlen=max_records)

    @property
    def is_persistence_bound(self) -> bool:
        return self._relational_memory is not None

    async def route(
        self,
        *,
        session_id: str,
        task_description: str,
        confidence: float | None = None,
    ) -> tuple[ToolRoute, str | None]:
        return await self.route_for_tools(
            session_id=session_id,
            tools_needed=(),
            task_description=task_description,
            confidence=confidence,
        )

    async def route_for_tools(
        self,
        *,
        session_id: str,
        tools_needed: tuple[str, ...],
        task_description: str = "",
        confidence: float | None = None,
    ) -> tuple[ToolRoute, str | None]:
        try:
            base = _keyword_route(task_description) if task_description else ToolRoute(
                primary_tool=(tools_needed[0] if tools_needed else "bash"),
                fallback_tools=tools_needed[1:] if len(tools_needed) > 1 else (),
                category=_CAPABILITY_TABLE.get(
                    tools_needed[0] if tools_needed else "bash", "unknown"
                ),
                reason=(
                    "Routed from SubTask.tools_needed"
                    if tools_needed
                    else "Default (no task description)"
                ),
            )
            matched = tuple(t for t in tools_needed if t in _CAPABILITY_TABLE)
            unrouted = tuple(t for t in tools_needed if t not in _CAPABILITY_TABLE)
            route = replace(
                base,
                matched_tools=matched,
                unrouted_tools=unrouted,
                id=f"route-{uuid.uuid4().hex[:8]}",
                created_at=datetime.now(timezone.utc).isoformat(),
            )
        except Exception:  # noqa: BLE001
            log.exception("tektos.tool_router: routing failed; returning fallback")
            route = ToolRoute(
                primary_tool="bash",
                fallback_tools=(),
                category="unknown",
                reason="fail-open fallback (ADR-107 D9)",
                matched_tools=(),
                unrouted_tools=tuple(tools_needed),
            )

        self._buffer.append(route)

        eff_conf = (
            float(confidence)
            if confidence is not None
            else TEKTOS_TOOL_ROUTER_DEFAULT_CONFIDENCE
        )

        narrative_id: str | None = None
        if self._relational_memory is not None:
            try:
                narrative_id = await self._relational_memory.write_narrative(
                    session_id=session_id,
                    agent_id=TEKTOS_TOOL_ROUTER_PROVENANCE,
                    title=f"{TEKTOS_TOOL_ROUTER_PREDICATE}:{route.id}",
                    body=json.dumps(_route_to_body(route), default=str),
                    tags=(
                        TEKTOS_TOOL_ROUTER_PROVENANCE,
                        route.category,
                        session_id,
                    ),
                    embedding=None,
                    confidence=eff_conf,
                    provenance=TEKTOS_TOOL_ROUTER_PROVENANCE,
                )
            except Exception:  # noqa: BLE001
                log.exception(
                    "tektos.tool_router: write_narrative failed; ring-buffer only"
                )

        if self._event_bus is not None:
            try:
                await self._event_bus.publish(
                    EventEnvelope(
                        event_type=TEKTOS_TOOL_ROUTER_PREDICATE,
                        producer_plugin=TEKTOS_TOOL_ROUTER_PROVENANCE,
                        payload={
                            "session_id": session_id,
                            "tools_requested": list(tools_needed),
                            "tools_matched": list(route.matched_tools),
                            "unrouted": list(route.unrouted_tools),
                            "primary_tool": route.primary_tool,
                            "category": route.category,
                            "narrative_id": narrative_id,
                        },
                    )
                )
            except Exception:  # noqa: BLE001
                log.exception(
                    "tektos.tool_router: EventBus publish failed; continuing"
                )

        return route, narrative_id

    def list_recent(self, limit: int = 10) -> tuple[ToolRoute, ...]:
        if limit <= 0:
            return ()
        return tuple(list(self._buffer)[-limit:])


